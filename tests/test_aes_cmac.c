#include "link/aes_cmac.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define CHECK(c) do { if (!(c)) { fprintf(stderr, "CHECK failed %s:%d: %s\n", __FILE__, __LINE__, #c); return EXIT_FAILURE; } } while (0)

int main(void)
{
    static const uint8_t key[16U] = {
        0x2bU,0x7eU,0x15U,0x16U,0x28U,0xaeU,0xd2U,0xa6U,
        0xabU,0xf7U,0x15U,0x88U,0x09U,0xcfU,0x4fU,0x3cU
    };
    static const uint8_t message[64U] = {
        0x6bU,0xc1U,0xbeU,0xe2U,0x2eU,0x40U,0x9fU,0x96U,0xe9U,0x3dU,0x7eU,0x11U,0x73U,0x93U,0x17U,0x2aU,
        0xaeU,0x2dU,0x8aU,0x57U,0x1eU,0x03U,0xacU,0x9cU,0x9eU,0xb7U,0x6fU,0xacU,0x45U,0xafU,0x8eU,0x51U,
        0x30U,0xc8U,0x1cU,0x46U,0xa3U,0x5cU,0xe4U,0x11U,0xe5U,0xfbU,0xc1U,0x19U,0x1aU,0x0aU,0x52U,0xefU,
        0xf6U,0x9fU,0x24U,0x45U,0xdfU,0x4fU,0x9bU,0x17U,0xadU,0x2bU,0x41U,0x7bU,0xe6U,0x6cU,0x37U,0x10U
    };
    static const uint8_t aes_zero_expected[16U] = {
        0x7dU,0xf7U,0x6bU,0x0cU,0x1aU,0xb8U,0x99U,0xb3U,0x3eU,0x42U,0xf0U,0x47U,0xb9U,0x1bU,0x54U,0x6fU
    };
    static const uint8_t tags[4U][16U] = {
        {0xbbU,0x1dU,0x69U,0x29U,0xe9U,0x59U,0x37U,0x28U,0x7fU,0xa3U,0x7dU,0x12U,0x9bU,0x75U,0x67U,0x46U},
        {0x07U,0x0aU,0x16U,0xb4U,0x6bU,0x4dU,0x41U,0x44U,0xf7U,0x9bU,0xddU,0x9dU,0xd0U,0x4aU,0x28U,0x7cU},
        {0xdfU,0xa6U,0x67U,0x47U,0xdeU,0x9aU,0xe6U,0x30U,0x30U,0xcaU,0x32U,0x61U,0x14U,0x97U,0xc8U,0x27U},
        {0x51U,0xf0U,0xbeU,0xbfU,0x7eU,0x3bU,0x9dU,0x92U,0xfcU,0x49U,0x74U,0x17U,0x79U,0x36U,0x3cU,0xfeU}
    };
    static const size_t lengths[4U] = {0U,16U,40U,64U};
    uint8_t block[16U] = {0U};
    uint8_t output[16U], tag[16U], wrong[16U];
    size_t index;

    CHECK(link_aes128_encrypt_block(key, block, output));
    CHECK(memcmp(output, aes_zero_expected, sizeof(output)) == 0);
    for (index = 0U; index < 4U; ++index) {
        const uint8_t *input = lengths[index] == 0U ? NULL : message;
        CHECK(link_aes_cmac_128(key, input, lengths[index], tag));
        CHECK(memcmp(tag, tags[index], sizeof(tag)) == 0);
        CHECK(link_aes_cmac_128_verify(key, input, lengths[index], tags[index]));
    }
    memcpy(wrong, tags[1U], sizeof(wrong));
    wrong[15U] ^= 1U;
    CHECK(!link_aes_cmac_128_verify(key, message, 16U, wrong));
    CHECK(!link_aes128_encrypt_block(NULL, block, output));
    CHECK(!link_aes128_encrypt_block(key, NULL, output));
    CHECK(!link_aes128_encrypt_block(key, block, NULL));
    CHECK(!link_aes_cmac_128(key, NULL, 1U, tag));
    CHECK(!link_aes_cmac_128(NULL, NULL, 0U, tag));
    CHECK(!link_aes_cmac_128(key, NULL, 0U, NULL));
    CHECK(!link_aes_cmac_128_verify(key, NULL, 0U, NULL));
    puts("AES-CMAC RFC 4493 vectors passed");
    return EXIT_SUCCESS;
}
